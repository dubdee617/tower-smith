// 親密度が EV_NEED 以上になると、それぞれの場面でランダムに一度だけ起こる。画像: assets/event/
const EV_NEED = 5;
const evReady = (who, chance) => (G.aff[who] || 0) >= EV_NEED && !(G.seen || {})[who] && R() < chance;
function evDone(who, pts) { G.seen = G.seen || {}; G.seen[who] = true; G.aff[who] = (G.aff[who] || 0) + pts; save(); }
// 場面の絵: bg=町の絵の名前（null なら塔の中）、pose=assets/event/ の名前
function evBg(bg) {
  if (!bg) return;
  place = { home_in: 'home', clinic_in: 'clinic', guild_in: 'guild' }[bg] || place; SND_INDOOR = true;
  showTown(true, 4 / 3); hud(); const t = $('town'); t.className = 'box town';
  t.innerHTML = `<img src="${TOWN_IMG}${bg}.jpg" alt="" style="filter:brightness(.5) saturate(.8)"><div class="portrait npc ev"><img alt=""></div>`;
}
function evPose(p) {
  const src = `assets/event/${p}.webp`;
  if (mode === 'dungeon') { const m = $('meet'); m.innerHTML = `<img src="${src}" alt="">`; m.style.display = 'flex'; m.classList.add('ev'); return; }
  const i = document.querySelector('#town .portrait.ev img'); if (i) { i.src = src; }
}
// 会話の流れ。{bg, p, t} または {p, t, ch:[[返事, 相手の反応, 親密度, 反応の絵]]}
function runEv(who, steps, done) {
  let i = 0;
  const next = () => {
    if (i >= steps.length) { done(); return; }
    const s = steps[i++]; if (s.bg) evBg(s.bg); if (s.p) evPose(s.p);
    if (s.rainStop) SND.scene = 'home';
    if (s.music !== undefined) SND.scene = s.music;  // その場面の曲（'romantic' など。'' で元に戻す）
    if (s.sfx) sfx(s.sfx);
    log(s.t, true);
    if (s.ch) { buttons(s.ch.map(([a, r, pt, p]) => ({ t: a, f: () => { G.aff[who] = (G.aff[who] || 0) + pt; if (p) evPose(p); log(r, true); buttons([{ t: '次へ', hot: true, f: next }]); } })), 'three'); return; }
    buttons([{ t: '次へ', hot: true, f: next }]);
  };
  next();
}

