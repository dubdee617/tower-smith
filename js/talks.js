// その人（場所）がまだ前回の話をしていなければ、ひとこと返す
function runLine(who) {
  const L = G.last, k = runKind(); if (!L || !k || L.run !== G.runs || !RUN_TALK[who]) return null;
  L.told = L.told || []; if (L.told.includes(who)) return null;
  L.told.push(who); save();
  return pick(RUN_TALK[who][k]).replace(/\{f\}/g, L.top).replace(/\{b\}/g, L.boss || L.top).replace(/\{k\}/g, L.kills || 0);
}
